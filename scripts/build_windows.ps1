param(
    [string]$BuildVersion = "0.1"
)

$ErrorActionPreference = "Stop"

if ($BuildVersion -notmatch '^\d+\.\d+$') {
    throw "BuildVersion must match MAJOR.MINOR without a leading v: $BuildVersion"
}

function Assert-NativeExitCode {
    param([string]$Step)

    if ($LASTEXITCODE -ne 0) {
        throw "$Step failed with exit code $LASTEXITCODE"
    }
}

$VersionModule = Join-Path $PSScriptRoot "../src/gdis_loader/_build_version.py"
$VersionModuleWritten = $false

try {
    uv sync --locked
    Assert-NativeExitCode "uv sync --locked"
    uv run ruff check .
    Assert-NativeExitCode "ruff check"
    uv run ruff format --check .
    Assert-NativeExitCode "ruff format --check"
    uv run ty check
    Assert-NativeExitCode "ty check"
    uv run pytest
    Assert-NativeExitCode "pytest"
    uv run python -c "from PySide6 import QtCore, QtWidgets; print(QtCore.qVersion())"
    Assert-NativeExitCode "PySide6 import"

    @"
"""Generated by scripts/build_windows.ps1; do not commit."""
BUILD_VERSION = "$BuildVersion"
"@ | Set-Content -Path $VersionModule -Encoding utf8NoBOM
    $VersionModuleWritten = $true

    uv run pyinstaller `
      --noconfirm `
      --clean `
      --onedir `
      --windowed `
      --name GDIS_DataLoader `
      --paths src `
      --add-data "config.example.toml;." `
      src/gdis_loader/__main__.py
    Assert-NativeExitCode "PyInstaller"

    $Executable = "dist/GDIS_DataLoader/GDIS_DataLoader.exe"
    if (-not (Test-Path $Executable)) {
        throw "PyInstaller did not create $Executable"
    }
    & $Executable --smoke-test --expected-version $BuildVersion
    Assert-NativeExitCode "Frozen GUI smoke-test"

    $ZipPath = "dist/GDIS_DataLoader-v$BuildVersion-windows-x64.zip"
    if (Test-Path $ZipPath) {
        Remove-Item $ZipPath -Force
    }
    Compress-Archive -Path "dist/GDIS_DataLoader" -DestinationPath $ZipPath
    Write-Host "Created $ZipPath"
}
finally {
    if ($VersionModuleWritten -and (Test-Path $VersionModule)) {
        Remove-Item $VersionModule -Force
    }
}
